"""Export the frozen P0 test set (4,187 canonical flights) to CSV + manifest.

Source: student_b/runs/canonical50k/data.npz (generated by experiment.generate
with seed=42; sha256 of the generator code is not tracked, so the manifest also
records the event counts that must match 41,733 airborne / 8,267 ground).

The CSV stores **clean** observations and endpoints. Evaluation noise is added
by the evaluator with the documented seeds, so every model sees identical
inputs. Do not train on this file.
"""
from __future__ import annotations

import csv
import hashlib
import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]  # student-c/P0/data -> repo root
DATA = ROOT / "student_b" / "runs" / "canonical50k" / "data.npz"
OUT_CSV = HERE / "test_canonical_4187.csv"
OUT_MANIFEST = HERE / "test_canonical_4187_manifest.json"


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def main():
    d = np.load(DATA)
    valid = (d["status"] == 1) & np.isfinite(d["observations"]).all(axis=(1, 2))
    test = np.flatnonzero(valid & (d["split"] == 2))
    assert len(test) == 4187, f"expected 4187 test flights, got {len(test)}"

    theta, obs, endpoint = d["theta"][test], d["observations"][test], d["endpoint"][test]
    columns = (["flight_id", "source_index", "split", "status"]
               + ["theta_vx", "theta_vy", "theta_vz", "theta_wx", "theta_wy",
                  "theta_wz", "theta_cd"]
               + ["obs005_x", "obs005_y", "obs005_z", "obs010_x", "obs010_y", "obs010_z"]
               + ["endpoint_y", "endpoint_z"])

    with open(OUT_CSV, "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(columns)
        for i, idx in enumerate(test):
            row = ([i, int(idx), 2, 1]
                   + [f"{v:.9f}" for v in theta[i]]
                   + [f"{v:.9f}" for v in obs[i].reshape(-1)]
                   + [f"{v:.9f}" for v in endpoint[i]])
            w.writerow(row)

    manifest = dict(
        name="P0 canonical test set",
        stage="P0",
        owner="student-c",
        created="2026-11-07",
        n_flights=len(test),
        source_file="student_b/runs/canonical50k/data.npz",
        generator="student_b/experiment.py::generate(n=50000, seed=42)",
        canonical_simulator="student_b/physics.py + student_b/params.json",
        filter="split==2 and status==1 (airborne goal-plane crossing) and finite observations",
        expected_event_counts={"airborne": 41733, "ground": 8267, "timeout": 0},
        expected_split_counts={"train": 33367, "val": 4179, "test": 4187},
        units="SI (m, m/s, rad/s); C_D dimensionless",
        observations="noise-free r(0.05) and r(0.10), 3 components each",
        endpoint="first forward crossing of x=11 m, (Y,Z)",
        noise_rule="add independent N(0, sigma^2) to each of the 6 observation coordinates",
        noise_seeds={
            "ablation_and_models": {"2mm": 11100, "5mm": 14100, "10mm": 19100, "15mm": 24100},
            "diagnostics_legacy_mdn": {"2mm": 11000, "5mm": 14000, "10mm": 19000, "15mm": 24000},
            "formula": "seed = 9100 (models) or 9000 (diagnostics) + int(sigma_m * 1e6)",
        },
        warning="Do not train, tune or calibrate on this file; it is the frozen P0 test set.",
        csv_columns=columns,
        csv_sha256=sha256(OUT_CSV),
        csv_bytes=OUT_CSV.stat().st_size,
    )
    OUT_MANIFEST.write_text(json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8")
    print("wrote", OUT_CSV, OUT_CSV.stat().st_size, "bytes")
    print("sha256", manifest["csv_sha256"])
    print("wrote", OUT_MANIFEST)


if __name__ == "__main__":
    main()
